export function localizeError(language: Language, error: unknown): string {
  const raw = error instanceof Error ? error.message : String(error)
  if (language === 'zh-CN') return raw
  let translated = raw
  for (const [chinese, english] of Object.entries(englishErrors).sort((a, b) => b[0].length - a[0].length)) {
    translated = translated.split(chinese).join(english)
  }
  translated = translated.replace(/；/g, '; ').replace(/，/g, ', ').replace(/（/g, '(').replace(/）/g, ')').replace(/。/g, '.')
  return /[\u3400-\u9fff]/.test(translated) ? 'Operation failed. Check the application logs for details.' : translated
}
